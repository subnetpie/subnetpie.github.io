import assert from 'node:assert/strict';
import {T2MatrixInputs} from './dist/t2-matrix.mjs';
const switches=new Map(),m=new T2MatrixInputs({setSwitch:(n,v)=>switches.set(n,v)});
const read=n=>switches.get(n),step=(time,...coils)=>m.update(time,n=>coils.includes(n));
assert.equal(read(33),1);for(const n of [31,32,33])assert.throws(()=>m.trigger(n),/managed/);
assert.throws(()=>m.trigger(76),/launch/);
step(0,4);step(350);assert(m.shooter);step(360,9);assert.equal(m.playfield,1);
m.trigger(77);assert.equal(read(77),1);step(370);assert.equal(read(77),1);step(380,28);assert.equal(read(77),0);
m.trigger(76);assert.equal(m.playfield,0);assert.equal(read(76),1);m.releaseHeld();assert.equal(read(76),1);
step(1000);assert.equal(read(31),0,'The ball must wait for the ROM popper coil');
step(1010,1);assert.equal(read(76),0);assert(m.gunTransfer);step(1509);assert.equal(read(31),0);step(1510);assert.equal(read(31),1);
assert.throws(()=>m.trigger(76),/gun to fire/);
step(2760,11);assert.equal(read(32),1);assert.equal(read(33),0);
step(3260,11);assert.equal(m.gunTarget(),71);assert.equal(read(32),0);
m.trigger(34);step(3300);assert.equal(read(31),1,'The trigger alone cannot manufacture a gun shot');
step(3320,2);assert.equal(read(31),0);assert(m.gunFiring);
step(3569);assert.equal(m.playfield,0);step(3570);assert.equal(m.playfield,1);assert.equal(read(71),1);
step(3690);assert.equal(read(71),0);assert.equal(m.trough+m.playfield,3,'Conserve the three balls through transfer and firing');
m.trigger(76);step(3900,1);assert(m.gunTransfer);m.reset();step(5000);assert.equal(read(31),0);assert.equal(m.transfer.length,0);assert.equal(read(33),1);
step(5010,12);assert.equal(read(77),1);step(5020,28);assert.equal(read(77),0);
console.log('T2 mechanism passed: coil-gated skull transfer and firing, automatic gun sensors, motor position and target hit, latched drop target, ball conservation and reset cleanup.');
