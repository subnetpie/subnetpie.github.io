import assert from 'node:assert/strict';
import {PopeyeMachine,popeyeEvents} from './dist/popeye-events.mjs';
const switches=new Map(),machine=new PopeyeMachine({setSwitch:(n,state)=>switches.set(n,state)});
assert.equal([...switches].filter(([n,v])=>n>=51&&n<=56&&v).length,6);
assert.throws(()=>machine.event('left-bumper'),/launch/);
machine.update(100,n=>n===5);assert.equal(machine.trough,5);
machine.update(180,()=>0);assert.equal(switches.get(57),1);
machine.update(300,()=>0);assert.equal(switches.get(57),0);
machine.update(450,()=>0);assert.equal(machine.shooter,true);assert.equal(switches.get(86),1);
machine.event('launch');machine.update(460,()=>0);assert.equal(switches.get(23),1);
machine.update(480,n=>n===3);assert.equal(machine.playfield,1);assert.equal(machine.shooter,false);assert.equal(switches.get(86),0);
machine.update(800,()=>0);assert.equal(switches.get(23),0);
machine.event('bumpers');assert.throws(()=>machine.event('left-inlane'),/finish/);
for(let t=800;t<2400;t+=10)machine.update(t,()=>0);
assert.equal(machine.snapshot().busy,false);for(const n of [16,17,18])assert.equal(switches.get(n),0);
machine.event('drain-left');assert.equal(machine.playfield,0);machine.update(2900,()=>0);assert.equal(machine.trough,6);
machine.reset();assert.equal(machine.trough,6);assert.equal(machine.shooter,false);assert.equal(machine.playfield,0);assert.equal(machine.pending.length,0);
machine.beginGame();assert.equal(machine.snapshot().starting,true);const queued=machine.pending.length;machine.beginGame();assert.equal(machine.pending.length,queued);machine.reset();assert.equal(machine.snapshot().starting,false);
assert.equal(new Set(popeyeEvents.map(e=>e.id)).size,popeyeEvents.length);
console.log('Popeye events passed: six-ball trough, coil-driven serving and launch, timed switches, event guards, drain return, and reset cleanup.');
