import assert from 'node:assert/strict';
import {LiveColorizer,planeCrc,splitPlanes} from './dist/live-colorizer.mjs';
assert.equal(planeCrc(new TextEncoder().encode('123456789')),0xcbf43926);
assert.equal(splitPlanes(Uint8Array.of(1,2,3,0,0,0,0,0),2)[0][0],5);
const palettes=[{id:0,default:true,colors:[[0,0,0],[255,130,0]]},{id:1,colors:[[0,0,0],[0,255,0]]}];
const raw=Uint8Array.of(1,0,1,0,0,0,0,0),second=Uint8Array.of(0,1,0,1,0,0,0,0),hash=planeCrc(splitPlanes(raw,2)[0]);
const frame=(value,extra={})=>({data:new Uint8Array(8).fill(value),delay:20,levels:16,...extra});
const mapping=(mode,extra={})=>({hash,mode,paletteId:1,offset:100,...extra});
const scene=(mode,frames,extra={})=>({mode,frames,w:8,h:1,offset:100,paletteId:1,...extra});
const create=(mappings,scenes=[],masks=[])=>new LiveColorizer({palettes,mappings,scenes,masks});
let engine=create([mapping(0,{duration:50})]);
assert.equal(engine.render(raw,8,1,2,0).colors,palettes[1].colors);
assert.equal(engine.render(raw,8,1,2,60).colors,palettes[0].colors);assert.equal(engine.matches,1,'repeated frames do not retrigger');
engine=create([mapping(1)],[scene(1,[frame(7),frame(9)])]);
assert.equal(engine.render(raw,8,1,2,0).data[0],7);assert.equal(engine.render(raw,8,1,2,25).data[0],9);assert.deepEqual(engine.render(raw,8,1,2,45).data,raw);
engine=create([mapping(2)],[scene(2,[frame(12)])]);assert.deepEqual([...engine.render(raw,8,1,2,0).data.slice(0,4)],[13,12,13,12]);
engine=create([mapping(4)],[scene(4,[frame(4,{hash:123}),frame(8,{hash:planeCrc(splitPlanes(second,2)[0])})])]);
engine.render(raw,8,1,2,0);assert.equal(engine.render(second,8,1,2,10).data[0],8);
const mask=Uint8Array.of(1),maskedHash=planeCrc(splitPlanes(raw,2)[0],mask);
engine=create([mapping(0,{hash:maskedHash})],[],[mask]);assert.equal(engine.render(raw,8,1,2,0).colors,palettes[1].colors);
engine=create([mapping(5)],[scene(5,[frame(8,{hash})])]);assert.equal(engine.render(raw,8,1,2,0).data[0],9);
engine=create([mapping(7)],[scene(7,[frame(10,{hash,mask:Uint8Array.of(1,0,0,0,0,0,0,0)})])]);assert.deepEqual([...engine.render(raw,8,1,2,0).data.slice(0,3)],[10,8,9]);
engine.reset();assert.equal(engine.matches,0);assert.equal(engine.active,null);
console.log('Live PAC: CRC/bit order, masked triggers, palette expiry, no repeated retrigger, timed replacement, color masks, follow, layered masks, masked replacement, and reset passed.');
